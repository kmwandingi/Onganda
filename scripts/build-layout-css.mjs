#!/usr/bin/env node
// ─── Onganda Design System — packaged layout stylesheet ─────────────────────
// A React component that positions itself with Tailwind utility classes only
// works if the CONSUMER runs Tailwind and points it at this package. That is
// documented, and it is still a trap: a consumer with no Tailwind at all —
// a browser extension, an embedded panel — imports the package, renders a
// StatCard, and gets a stack of unstyled text because `flex-col` was never
// compiled anywhere.
//
// That happened. The FirstRung side panel loads only this package's
// stylesheet, and its CSS contained zero flex rules, so the stat band
// collapsed into an unreadable jumble.
//
// So the package ships the utilities its own components use. Compiled by
// Tailwind from the component source, never hand-written, so it cannot drift
// from the classes the components actually carry.
//
//   node scripts/build-layout-css.mjs

import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { compile } from 'tailwindcss';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(HERE, '..');
const SRC = path.join(root, 'src/components/onganda');
const OUT = path.join(root, 'src/design-system/lib-layout.css');

// Every class the package's own components carry. Read from source, so a new
// class in a component appears here on the next build.
const files = [
  'onganda-primitives.tsx',
  'onganda-patterns.tsx',
  'onganda-site.tsx',
  'onganda-icons.tsx',
  'onganda-charts.tsx'
].filter(f => existsSync(path.join(SRC, f)));

const candidates = new Set();
for (const f of files) {
  const text = readFileSync(path.join(SRC, f), 'utf8');
  for (const m of text.matchAll(/className=(?:\{`|["'])([^"'`]*)/g)) {
    for (const cls of m[1].split(/\s+/)) {
      // Skip template holes and this package's own semantic classes.
      if (!cls || cls.includes('${') || cls.startsWith('onganda-')) continue;
      candidates.add(cls);
    }
  }
}
if (candidates.size < 50) throw new Error(`build-layout-css: only ${candidates.size} classes found — the scanner is wrong`);

const input = `@layer theme, base, components, utilities;
@import 'tailwindcss/theme.css' layer(theme);
@import 'tailwindcss/utilities.css' layer(utilities);
`;

const compiler = await compile(input, {
  base: root,
  loadStylesheet: async (id, base) => {
    const resolved = id.startsWith('tailwindcss/')
      ? path.join(root, 'node_modules', id)
      : path.resolve(base, id);
    return { path: resolved, base: path.dirname(resolved), content: readFileSync(resolved, 'utf8') };
  }
});

const css = compiler.build([...candidates]);

const header = `/*
 * Onganda Design System — packaged layout utilities
 *
 * GENERATED by scripts/build-layout-css.mjs. Do not edit.
 *
 * These are the utility classes this package's own components carry, compiled
 * here so the components lay themselves out in ANY consumer — including one
 * with no Tailwind at all. A consumer that does run Tailwind is unaffected:
 * the rules are identical to the ones it would generate.
 *
 * ${candidates.size} classes, read from the component source at build time.
 */
`;

writeFileSync(OUT, header + css);
console.log(`Wrote ${path.relative(root, OUT)} — ${candidates.size} classes, ${(css.length / 1024).toFixed(1)} kB`);
