#!/usr/bin/env node
// ─── Onganda Design System — embedded faces ─────────────────────────────────
// Writes src/design-system/fonts.css: @font-face rules for Inter and Space
// Grotesk with the woff2 files embedded as data URIs, so the faces load in any
// bundler. `--check` fails when the file is stale.

import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const dir = path.join(root, 'src/design-system/fonts');
const out = path.join(root, 'src/design-system/fonts.css');

const LATIN = 'U+0000-00FF,U+0131,U+0152-0153,U+02BB-02BC,U+02C6,U+02DA,U+02DC,U+0304,U+0308,U+0329,U+2000-206F,U+20AC,U+2122,U+2191,U+2193,U+2212,U+2215,U+FEFF,U+FFFD';
// Latin Extended carries the macrons and circumflexes of Khoekhoegowab and
// Otjiherero, so it is not optional here.
const EXT = 'U+0100-02BA,U+02BD-02C5,U+02C7-02CC,U+02CE-02D7,U+02DD-02FF,U+0304,U+0308,U+0329,U+1D00-1DBF,U+1E00-1E9F,U+1EF2-1EFF,U+2020,U+20A0-20AB,U+20AD-20C0,U+2113,U+2C60-2C7F,U+A720-A7FF';

const FACES = [
  ['Inter', '100 900', 'inter-latin-wght-normal.woff2', LATIN],
  ['Inter', '100 900', 'inter-latin-ext-wght-normal.woff2', EXT],
  ['Space Grotesk', '300 700', 'space-grotesk-latin-wght-normal.woff2', LATIN],
  ['Space Grotesk', '300 700', 'space-grotesk-latin-ext-wght-normal.woff2', EXT]
];

const face = ([family, weight, file, range]) => `@font-face {
  font-family: '${family}';
  font-style: normal;
  font-display: swap;
  font-weight: ${weight};
  src: url('data:font/woff2;base64,${readFileSync(path.join(dir, file)).toString('base64')}') format('woff2');
  unicode-range: ${range};
}`;

const body = `/*
 * Onganda Design System — the two faces, shipped with the package
 *
 * Inter (body, interface) and Space Grotesk (headings), variable, Latin and
 * Latin Extended. SIL Open Font License 1.1 — see fonts/LICENSE-*.txt.
 *
 * These used to load from Google Fonts with a remote @import at the top of
 * style.css. CSS only honours @import before every other rule, so a product
 * importing style.css after 'tailwindcss' — as every Tailwind app does —
 * silently dropped it, and every heading fell back to Inter or Arial. A
 * local-first product should not depend on a font CDN either.
 *
 * The files are embedded as data URIs. A url('./fonts/…') is only found if
 * the consumer's bundler rewrites URLs through nested @imports, and Tailwind's
 * Vite plugin does not — the showcase itself rendered in Arial that way.
 *
 * GENERATED by scripts/build-font-css.mjs from src/design-system/fonts/.
 */
${FACES.map(face).join('\n')}\n`;

if (process.argv.includes('--check')) {
  if (!existsSync(out) || readFileSync(out, 'utf8') !== body) {
    console.error('src/design-system/fonts.css is stale. Run `npm run build:fonts` and commit the result.');
    process.exit(1);
  }
  console.log('Embedded faces are current.');
} else {
  writeFileSync(out, body);
  console.log(`Wrote fonts.css — ${FACES.length} faces, ${Math.round(body.length / 1024)} kB`);
}
