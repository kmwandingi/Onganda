#!/usr/bin/env node
// ─── Onganda Design System — semantic tokens as CSS ─────────────────────────
// Until this existed, the only CSS custom properties the package shipped were
// the thirteen raw pigments. None of the 42 colour roles, none of the type
// steps, spacing, texture or rules were reachable from CSS.
//
// That quietly undid the role layer. An agent styling in CSS or Tailwind
// could reach `--onganda-mahangu-gold` but not `--onganda-text-muted`, so
// "use the design tokens" meant "use the palette", and the palette is exactly
// what produces colour everywhere. Handing Figma a token file works because
// the tokens are SEMANTIC; this is that file.
//
// Values are read from the real `roles()` and scale objects, bundled from
// source with esbuild, so the CSS cannot disagree with the components.
//
//   node scripts/build-token-css.mjs          (run by build:lib)
//
// Writes src/design-system/tokens.css (vars, both modes) and
// src/design-system/tailwind.css (a Tailwind 4 @theme mapping). Both are
// committed, like tokens/onganda.tokens.json, so an agent can open one file
// and read the entire vocabulary. `--check` fails when they are stale.

import { build } from 'esbuild';
import { writeFileSync, readFileSync, existsSync, mkdtempSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { fileURLToPath, pathToFileURL } from 'node:url';
import path from 'node:path';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const src = path.join(root, 'src/components/onganda');
const tmp = mkdtempSync(path.join(tmpdir(), 'onganda-tokens-'));
const entry = path.join(tmp, 'entry.mjs');
const outfile = path.join(tmp, 'tokens.mjs');

writeFileSync(entry, `
export { roles, ACCENT_CYCLE, statusFor, SYSTEM_COLOR } from ${JSON.stringify(path.join(src, 'onganda-roles.ts'))};
export { TYPE, SPACE_SCALE, TEXTURE, RULE, GEOMETRY, FONT } from ${JSON.stringify(path.join(src, 'onganda-type.ts'))};
`);
await build({ entryPoints: [entry], bundle: true, format: 'esm', platform: 'node', outfile, logLevel: 'silent' });
const t = await import(pathToFileURL(outfile).href);
rmSync(tmp, { recursive: true, force: true });

const kebab = s => s.replace(/([a-z0-9])([A-Z])/g, '$1-$2').toLowerCase();
const px = v => (typeof v === 'number' ? `${v}px` : v);

const light = t.roles(false);
const dark = t.roles(true);
const roleNames = Object.keys(light);
if (roleNames.length < 30) throw new Error(`build-token-css: only ${roleNames.length} roles read — source changed shape`);

const roleBlock = r => roleNames.map(k => `  --onganda-${kebab(k)}: ${r[k]};`).join('\n');
const status = dk => ['active', 'caution', 'critical', 'settled']
  .map(s => `  --onganda-status-${s}: ${t.statusFor(s, dk)};`).join('\n');

const typeBlock = Object.entries(t.TYPE).map(([step, v]) => [
  `  --onganda-type-${kebab(step)}-size: ${v.size}px;`,
  `  --onganda-type-${kebab(step)}-weight: ${v.weight};`,
  `  --onganda-type-${kebab(step)}-leading: ${v.lineHeight};`,
  `  --onganda-type-${kebab(step)}-tracking: ${v.tracking};`
].join('\n')).join('\n');

const css = `/*
 * Onganda Design System — semantic tokens
 *
 * GENERATED by scripts/build-token-css.mjs from roles() and the scales in
 * onganda-type.ts. Do not edit.
 *
 * READ A ROLE, NOT A PIGMENT. \`--onganda-text-muted\`, not
 * \`--onganda-mopane-brown\`. The pigment variables still exist for identity
 * (a system's own colour), but a surface, a line, a label or a control reads
 * its role. That is the whole difference between following the system and
 * using its palette.
 *
 * Light is the default. Dark applies under any of:
 *   [data-onganda-theme="dark"]  — set on <html> by <DarkProvider>
 *   [data-theme="dark"]  .dark   — the common conventions
 */

:root {
  /* ── Colour roles ───────────────────────────────────────────── */
${roleBlock(light)}

  /* ── Status: the four states, and never the only signal ─────── */
${status(false)}

  /* ── Accents for PEER CARDS in a list, in the site's order ──── */
  /* Not for tags, metadata or chrome — see DESIGN_GUIDELINES.md.   */
${t.ACCENT_CYCLE.map((c, i) => `  --onganda-accent-${i + 1}: ${c};`).join('\n')}

  /* ── Type: the closed scale ─────────────────────────────────── */
${typeBlock}
  --onganda-font-body: ${t.FONT.family};
  --onganda-font-heading: ${t.FONT.display};

  /* ── Space: the 4px grid ────────────────────────────────────── */
${Object.entries(t.SPACE_SCALE).map(([k, v]) => `  --onganda-space-${k}: ${px(v)};`).join('\n')}

  /* ── Texture: grounds and inverse panels; never stacked ─────── */
${Object.entries(t.TEXTURE).map(([k, v]) => `  --onganda-texture-${kebab(k)}: ${v};`).join('\n')}

  /* ── Rules: solid hairlines; most blocks need none ─────────── */
${Object.entries(t.RULE).map(([k, v]) => `  --onganda-rule-${kebab(k)}-height: ${v.height}px;\n  --onganda-rule-${kebab(k)}-opacity: ${v.opacity};`).join('\n')}

  /* ── Geometry: no radius, no elevation ──────────────────────── */
  --onganda-radius: ${t.GEOMETRY.radius}px;
  --onganda-shadow: ${t.GEOMETRY.shadow};
  --onganda-border-hairline: ${t.GEOMETRY.borderWidths[0]}px;
  --onganda-border-spine: ${t.GEOMETRY.borderWidths[1]}px;
}

:root[data-onganda-theme="dark"],
[data-theme="dark"],
.dark {
${roleBlock(dark)}
${status(true)}
}
`;

// Tailwind 4 reads @theme. Mapping the roles into it is what makes
// \`bg-surface text-muted border-line\` the easy utilities, instead of
// \`bg-[#F3E8C3]\` or a raw pigment. \`inline\` keeps the var() reference, so
// the utilities follow dark mode instead of freezing the light value.
const tw = `/*
 * Onganda Design System — Tailwind 4 theme
 *
 * GENERATED by scripts/build-token-css.mjs. Do not edit.
 *
 *   @import 'tailwindcss';
 *   @import '@onganda/design-system/tailwind.css';
 *
 * Then \`bg-surface\`, \`text-text-muted\`, \`border-line\`, \`bg-action-bg\`,
 * \`text-eyebrow\`, \`p-6\` on the 4px grid. Tailwind's own colour palette is
 * reset so \`bg-blue-500\` stops existing — the system has no blue, and a
 * utility that compiles is a utility an agent will use.
 */

@theme inline {
  --color-*: initial;
${roleNames.map(k => `  --color-${kebab(k)}: var(--onganda-${kebab(k)});`).join('\n')}
${['active', 'caution', 'critical', 'settled'].map(s => `  --color-status-${s}: var(--onganda-status-${s});`).join('\n')}
${t.ACCENT_CYCLE.map((_, i) => `  --color-accent-${i + 1}: var(--onganda-accent-${i + 1});`).join('\n')}

  --font-sans: var(--onganda-font-body);
  --font-heading: var(--onganda-font-heading);

${Object.entries(t.TYPE).map(([step, v]) => `  --text-${kebab(step)}: ${v.size}px;\n  --text-${kebab(step)}--line-height: ${v.lineHeight};\n  --text-${kebab(step)}--letter-spacing: ${v.tracking};\n  --text-${kebab(step)}--font-weight: ${v.weight};`).join('\n')}

  --radius-*: initial;
  --shadow-*: initial;
}
`;

const outputs = [
  [path.join(root, 'src/design-system/tokens.css'), css],
  [path.join(root, 'src/design-system/tailwind.css'), tw]
];

if (process.argv.includes('--check')) {
  const stale = outputs.filter(([f, body]) => !existsSync(f) || readFileSync(f, 'utf8') !== body);
  if (stale.length) {
    console.error(`${stale.map(([f]) => path.relative(root, f)).join(', ')} stale — the token sources changed.`);
    console.error('Run `npm run build:token-css` and commit the result.');
    process.exit(1);
  }
  console.log(`Token CSS is current — ${roleNames.length} roles in both modes.`);
} else {
  for (const [f, body] of outputs) writeFileSync(f, body);
  console.log(`Wrote tokens.css (${roleNames.length} roles x2, ${Object.keys(t.TYPE).length} type steps) and tailwind.css`);
}
